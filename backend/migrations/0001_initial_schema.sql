-- ReliefLens schema for PostgreSQL / Supabase.
-- Mirrors backend/app/db.py (same tables and column names, so the API is unchanged).
-- Apply with:  cd backend && python -m app.migrate
-- Safe to re-run: every statement checks whether its object already exists.

-- Reports from every channel (web form, SMS, WhatsApp, helpline call).
create table if not exists public.reports (
    id                      text primary key,                -- UUID string generated by the backend
    reference               text not null,                   -- short public reference, e.g. RL-81BE
    created_at              timestamptz not null default now(),
    updated_at              timestamptz not null default now(),
    is_synthetic            boolean not null default false,  -- demo/sample data label
    channel                 text not null,
    sender_contact          text,                            -- phone number (personal data; reviewers only)
    sender_hash             text,                            -- keyed hash of the number, for "same sender" hints
    provider_message_id     text,                            -- SMS/WhatsApp/call id; makes webhook retries idempotent
    source_text             text not null,
    masked_text             text not null,                   -- phone numbers masked
    submitted_place_text    text,
    submitted_lat           double precision,
    submitted_lng           double precision,
    image_path              text,                            -- file name in UPLOAD_DIR
    audio_path              text,                            -- call recording or web voice note
    call_duration_seconds   double precision,
    transcript_status       text,
    transcript_model        text,
    transcript_error        text,
    helpline_number         text,
    helpline_label          text,
    intake_notes            jsonb not null default '[]'::jsonb,
    status                  text not null default 'pending_review',
    urgency                 text not null default 'unknown',
    urgency_set_by_reviewer boolean not null default false,
    merged_into             text,
    reviewer_fields         jsonb not null default '{}'::jsonb,  -- reviewer corrections (needs, quantities, place...)
    constraint reports_reference_key unique (reference),
    constraint reports_provider_message_id_key unique (provider_message_id),
    constraint reports_merged_into_fkey foreign key (merged_into) references public.reports (id) on delete set null,
    constraint reports_status_check check (status in ('pending_review', 'approved', 'rejected', 'flagged', 'merged')),
    constraint reports_urgency_check check (urgency in ('low', 'medium', 'high', 'unknown')),
    constraint reports_channel_check check (channel in ('web', 'sms', 'whatsapp', 'call')),
    constraint reports_transcript_status_check
        check (transcript_status is null or transcript_status in ('pending', 'running', 'succeeded', 'failed', 'manual')),
    constraint reports_submitted_point_check check (
        (submitted_lat is null) = (submitted_lng is null)
        and (submitted_lat is null or (submitted_lat between -90 and 90 and submitted_lng between -180 and 180))),
    constraint reports_call_duration_check check (call_duration_seconds is null or call_duration_seconds >= 0),
    constraint reports_not_merged_into_itself check (merged_into is null or merged_into <> id)
);
create index if not exists ix_reports_created_at on public.reports (created_at);
create index if not exists ix_reports_status on public.reports (status);
create index if not exists ix_reports_sender_hash on public.reports (sender_hash);
create index if not exists ix_reports_merged_into on public.reports (merged_into);

-- AI extraction result for each report (one row per report).
create table if not exists public.extractions (
    report_id    text primary key references public.reports (id) on delete cascade,
    status       text not null default 'pending',
    model        text,
    attempts     integer not null default 0,
    language     text,
    output       jsonb,
    raw_response text,
    error        text,
    completed_at timestamptz,
    constraint extractions_status_check check (status in ('pending', 'running', 'succeeded', 'failed')),
    constraint extractions_attempts_check check (attempts >= 0)
);

-- Suggested and reviewer-confirmed location for each report. Only confirmed points reach the public map.
create table if not exists public.locations (
    report_id        text primary key references public.reports (id) on delete cascade,
    suggested_lat    double precision,
    suggested_lng    double precision,
    suggested_label  text,
    confirmed_lat    double precision,
    confirmed_lng    double precision,
    confirmed_label  text,
    confirmed_source text,
    confirmed_at     timestamptz,
    constraint locations_confirmed_source_check
        check (confirmed_source is null or confirmed_source in ('submitter_pin', 'geocoder_candidate', 'reviewer_pin')),
    constraint locations_suggested_point_check check (
        (suggested_lat is null) = (suggested_lng is null)
        and (suggested_lat is null or (suggested_lat between -90 and 90 and suggested_lng between -180 and 180))),
    constraint locations_confirmed_point_check check (
        (confirmed_lat is null) = (confirmed_lng is null)
        and (confirmed_lat is null or (confirmed_lat between -90 and 90 and confirmed_lng between -180 and 180)))
);

-- Audit trail: every status change, review, merge and export. No foreign key on report_id on purpose:
-- export events use report_id = 'export'.
create table if not exists public.audit_log (
    id          bigint generated by default as identity primary key,
    report_id   text not null,
    at          timestamptz not null default now(),
    actor       text not null,
    action      text not null,
    from_status text,
    to_status   text,
    details     jsonb,
    note        text
);
create index if not exists ix_audit_log_report_id on public.audit_log (report_id);
-- "When was this report approved?" for the public map and exports.
create index if not exists ix_audit_log_approved on public.audit_log (report_id, at) where to_status = 'approved';

-- Help categories (six built-ins are added by the backend at startup; organizers add more).
create table if not exists public.categories (
    key        text primary key,
    label      text not null,
    label_ur   text,
    keywords   jsonb not null default '[]'::jsonb,
    builtin    boolean not null default false,
    active     boolean not null default true,
    position   integer not null default 0,
    created_at timestamptz not null default now()
);

-- Helpline numbers people call or text.
create table if not exists public.helplines (
    id              text primary key,
    number          text not null,
    label           text not null,
    provider_number text,
    active          boolean not null default true,
    created_at      timestamptz not null default now(),
    constraint helplines_number_key unique (number)
);

-- Cached place-search results (no personal data).
create table if not exists public.geocode_cache (
    query_norm text primary key,
    results    jsonb not null,
    fetched_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------------------------
-- Security. Browsers never talk to this database: only the FastAPI backend does, and it enforces
-- the reviewer sign-in. Supabase also publishes every table in `public` through its REST/GraphQL
-- API with the anon key, so lock that door: Row Level Security on, no policies for the public
-- `anon` / `authenticated` roles, and their table privileges removed.
-- ---------------------------------------------------------------------------------------------
alter table public.reports       enable row level security;
alter table public.extractions   enable row level security;
alter table public.locations     enable row level security;
alter table public.audit_log     enable row level security;
alter table public.categories    enable row level security;
alter table public.helplines     enable row level security;
alter table public.geocode_cache enable row level security;

do $$
declare
    r text;
begin
    foreach r in array array['anon', 'authenticated'] loop
        if exists (select 1 from pg_roles where rolname = r) then
            execute format('revoke all on table public.reports, public.extractions, public.locations, '
                           'public.audit_log, public.categories, public.helplines, public.geocode_cache from %I', r);
            execute format('revoke all on sequence public.audit_log_id_seq from %I', r);
        end if;
    end loop;
end
$$;
